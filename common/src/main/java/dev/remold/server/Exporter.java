package dev.remold.server;

import com.google.gson.JsonElement;
import com.google.gson.JsonParser;
import dev.remold.data.ChangeEntry;
import net.minecraft.server.MinecraftServer;

import java.io.IOException;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.stream.Stream;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

public final class Exporter {
    private Exporter() {}

    public record Result(Path zip, Path kubejs) {}

    public static Result export(MinecraftServer server) throws IOException {
        RemoldPack pack = RemoldPack.get(server);
        pack.flush();
        Path outDir = server.getServerDirectory().resolve("remold-exports");
        Files.createDirectories(outDir);
        String stamp = LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyyMMdd-HHmmss"));
        Path zip = outDir.resolve("remold-pack-" + stamp + ".zip");
        Path root = pack.root();
        try (OutputStream out = Files.newOutputStream(zip); ZipOutputStream zos = new ZipOutputStream(out)) {
            if (Files.isDirectory(root)) {
                try (Stream<Path> files = Files.walk(root)) {
                    for (Path file : (Iterable<Path>) files.filter(Files::isRegularFile)::iterator) {
                        zos.putNextEntry(new ZipEntry(root.relativize(file).toString().replace('\\', '/')));
                        Files.copy(file, zos);
                        zos.closeEntry();
                    }
                }
            }
        }
        Path kubejs = outDir.resolve("remold-" + stamp + ".js");
        Files.writeString(kubejs, kubeJsScript(pack), StandardCharsets.UTF_8);
        return new Result(zip, kubejs);
    }

    private static String jsList(java.util.List<String> entries) {
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < entries.size(); i++) {
            if (i > 0) sb.append(", ");
            sb.append('\'').append(entries.get(i)).append('\'');
        }
        return sb.append(']').toString();
    }

    static String kubeJsScript(RemoldPack pack) throws IOException {
        StringBuilder js = new StringBuilder();
        js.append("// Generated by Remold. Put this file in kubejs/server_scripts/\n");
        js.append("// (Not needed if you use the exported datapack instead.)\n\n");
        js.append("ServerEvents.recipes(event => {\n");
        for (ChangeEntry change : pack.changes()) {
            String id = change.id().toString();
            if (change.kind() == ChangeEntry.Kind.REMOVED) {
                js.append("  event.remove({ id: '").append(id).append("' })\n");
                continue;
            }
            if (change.kind() == ChangeEntry.Kind.REPLACED) {
                js.append("  event.remove({ id: '").append(id).append("' })\n");
            }
            Path file = pack.recipeFile(change.id());
            if (!Files.isRegularFile(file)) continue;
            JsonElement json = JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8));
            js.append("  event.custom(").append(json).append(").id('").append(id).append("')\n");
        }
        js.append("})\n");
        if (!pack.tagEdits().isEmpty()) {
            js.append("\nServerEvents.tags('item', event => {\n");
            pack.tagEdits().forEach((tag, edit) -> {
                if (!edit.add().isEmpty()) js.append("  event.add('").append(tag).append("', ").append(jsList(edit.add())).append(")\n");
                if (!edit.remove().isEmpty()) js.append("  event.remove('").append(tag).append("', ").append(jsList(edit.remove())).append(")\n");
            });
            js.append("})\n");
        }
        return js.toString();
    }
}
